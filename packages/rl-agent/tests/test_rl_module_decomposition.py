def test_sim_translation_preserves_legal_action_order_and_ids() -> None:
    raw_actions = [
        {"action": "play_card", "card_index": 0, "target_id": 7},
        {"action": "use_potion", "slot": 0, "target_id": 7},
        {"action": "end_turn"},
    ]
    translated = translate_to_bridge_shape(
        {
            "state_type": "combat",
            "battle": {
                "player": {
                    "current_hp": 44,
                    "max_hp": 80,
                    "hand": [{"index": 0, "id": "CARD.STRIKE", "name": "Strike"}],
                    "potions": [{"slot": 0, "id": "POTION.FIRE", "name": "Fire Potion"}],
                },
                "enemies": [
                    {
                        "combat_id": 7,
                        "name": "Jaw Worm",
                        "current_hp": 33,
                        "max_hp": 40,
                    }
                ],
            },
            "legal_actions": raw_actions,
        },
        episode_id="compatibility-test",
    )["available_actions"]

    assert [action["idx"] for action in translated] == [0, 1, 2]
    assert [action["action_index"] for action in translated] == [0, 1, 2]
    assert [action["kind"] for action in translated] == ["play_card", "use_potion", "end_turn"]
    assert [action["action_id"] for action in translated] == [
        "sim:play_card:card_index=0:target_id=7",
        "sim:use_potion:slot=0:target_id=7",
        "sim:end_turn",
    ]
    assert [action["_sim_raw"] for action in translated] == raw_actions
