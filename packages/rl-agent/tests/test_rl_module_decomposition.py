def test_compatibility_facades_keep_public_symbols_and_historical_type_homes() -> None:
    from muzero.sts2_env.muzero_model import ActionRolloutPlannerOutput
    from muzero.sts2_env.token_memory import (
        EntityTokenEmbedder,
        TokenDynamicsNetwork,
        TokenFutureWorldBankHead,
        TokenLatentProjector,
        TokenMemoryEncoder,
        TokenMemoryEncoderOutput,
        TokenPredictionNetwork,
        TokenTransitionSurfaceHead,
    )
    from sts2_env._sim_translate import SelfInflictedHpTracker, sim_kind_to_bridge_kind
    from sts2_env.combat_env import CombatSandboxEnv, CurriculumTracker, get_curriculum_tracker
    from sts2_env.env_v2 import SlayTheSpire2EnvV2
    from sts2_env.observation_v3 import ObservationEncoderV3, WorldTokenObservationEncoder

    assert ObservationEncoderV3 is WorldTokenObservationEncoder
    expected_type_homes = {
        WorldTokenObservationEncoder: "sts2_env.observation_v3",
        CombatSandboxEnv: "sts2_env.combat_env",
        CurriculumTracker: "sts2_env.combat_env",
        SlayTheSpire2EnvV2: "sts2_env.env_v2",
        SelfInflictedHpTracker: "sts2_env._sim_translate",
        EntityTokenEmbedder: "muzero.sts2_env.token_memory",
        TokenDynamicsNetwork: "muzero.sts2_env.token_memory",
        TokenFutureWorldBankHead: "muzero.sts2_env.token_memory",
        TokenLatentProjector: "muzero.sts2_env.token_memory",
        TokenMemoryEncoder: "muzero.sts2_env.token_memory",
        TokenMemoryEncoderOutput: "muzero.sts2_env.token_memory",
        TokenPredictionNetwork: "muzero.sts2_env.token_memory",
        TokenTransitionSurfaceHead: "muzero.sts2_env.token_memory",
        ActionRolloutPlannerOutput: "muzero.sts2_env.muzero_model",
        MuZeroNetwork: "muzero.sts2_env.muzero_model",
    }
    for symbol, expected_module in expected_type_homes.items():
        assert symbol.__module__ == expected_module

    # Functions that used to be defined in the facades remain resolvable from
    # their old pickle/introspection homes too.
    assert get_curriculum_tracker.__module__ == "sts2_env.combat_env"
    assert sim_kind_to_bridge_kind.__module__ == "sts2_env._sim_translate"
    assert muzero_model.scalar_to_support.__module__ == "muzero.sts2_env.muzero_model"
    assert token_memory.build_memory_slot_bank_ids.__module__ == "muzero.sts2_env.token_memory"

    # Representative historically importable constants/helpers guard against
    # an over-aggressive facade cleanup silently breaking out-of-tree callers.
    assert {
        "DEFAULT_EFFECT_PROFILE",
        "MAX_HISTORY_TOKENS",
        "OWNER_HAND",
        "TOKEN_TYPES",
        "_CARD_KEYWORD_BUCKETS",
        "_resolve_potion_effect",
    } <= set(observation_v3.__all__)
    assert {
        "CrossAttentionBlock",
        "MAX_WORLD_TOKENS",
        "TokenMemoryEncoder",
        "build_zone_transport_prior",
    } <= set(token_memory.__all__)
    assert {
        "DEFAULT_ACTION_ROLLOUT_BUCKETS",
        "MuZeroNetwork",
        "SEMANTIC_ROLLOUT_FEAT_DIM",
        "scalar_to_support",
    } <= set(muzero_model.__all__)


def _small_token_network() -> MuZeroNetwork:
    return MuZeroNetwork(
        obs_mode="token_v3",
        model_arch="token_memory_v1",
        action_embed_dim=8,
        token_d_model=16,
        token_n_heads=2,
        token_ffn_dim=32,
        token_world_layers=1,
        token_local_layers=1,
        token_decoder_layers=1,
        token_candidate_set_layers=0,
        token_memory_slots=8,
        token_world_bank_top_k=5,
        token_bank_token_slots=1,
    )


def test_token_muzero_checkpoint_surface_matches_pre_split_golden() -> None:
    torch.manual_seed(123)
    network = _small_token_network()
    state = network.state_dict()
    surface = "\n".join(f"{key}:{tuple(value.shape)}" for key, value in state.items())

    # Generated by the pre-split MuZeroNetwork with the constructor above.
    assert len(state) == 1803
    assert hashlib.sha256(surface.encode()).hexdigest() == (
        "ce8da0e51b4d3038873c0daa424905e95f383b8d8984e7955626a495f806857a"
    )
    assert not any("_muzero_action_rollout" in key or "_token_memory_" in key for key in state)

    clone = _small_token_network()
    incompatible = clone.load_state_dict(state, strict=True)
    assert incompatible.missing_keys == []
    assert incompatible.unexpected_keys == []


